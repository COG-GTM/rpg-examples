-- ---------------------------------------------------------------------
-- DB2 for i external stored procedures over service program CLIESRV.
-- Callable from JDBC/ODBC (Java, Node, .NET) or a REST layer such as
-- IBM i Integrated Web Services or a Spring Boot service.
--
-- Replace CLIELIB with the library that holds CLIESRV and TRCLIE.
--
-- Every procedure returns the same OUT parameters:
--   P_STATUS   0 ok | 10 DNI invalid | 20 DNI exists | 30 not found
--              40 soft-deleted | 50 record locked | 99 I/O error
--   P_MESSAGE  human-readable text
--   P_NAME .. P_ACTIVE  image of the TRCLIE record after the operation
--              (blank / 0001-01-01-00.00.00 when P_STATUS <> 0)
-- ---------------------------------------------------------------------

CREATE OR REPLACE PROCEDURE CLIELIB.CLIENT_CREATE (
  IN  P_DNI        NUMERIC(8, 0),
  IN  P_NAME_IN    CHAR(30),
  IN  P_ACTOR      CHAR(10),
  OUT P_STATUS     INTEGER,
  OUT P_MESSAGE    VARCHAR(80),
  OUT P_NAME       CHAR(30),
  OUT P_CREATED_TS TIMESTAMP,
  OUT P_CREATED_BY CHAR(10),
  OUT P_UPDATED_TS TIMESTAMP,
  OUT P_UPDATED_BY CHAR(10),
  OUT P_DELETED_TS TIMESTAMP,
  OUT P_DELETED_BY CHAR(10),
  OUT P_ACTIVE     CHAR(1))
  LANGUAGE RPGLE
  SPECIFIC CLIELIB.CLICREATE
  NOT DETERMINISTIC
  NO SQL
  EXTERNAL NAME 'CLIELIB/CLIESRV(CLIENTCREATESQL)'
  PARAMETER STYLE GENERAL
  PROGRAM TYPE SUB;

